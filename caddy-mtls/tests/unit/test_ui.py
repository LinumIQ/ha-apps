"""Unit tests for the panel's look: the shared LinumIQ UI (shared/ui, copied
into static/shared/ and templates/_layout.html by scripts/sync-shared.sh),
the app's templates and static files.

Standard library only; the rendering tests also need Jinja2 (installed in
the add-on image's virtualenv) and are skipped without it. Runs against the
repository's panel, or the installed one with CERT_MGR_DIR - see
test_monitor.py. The smoke test (tests/smoke.sh) checks the same files as
the running panel serves them.
"""
from __future__ import annotations

import hashlib
import os
import re
import sys
import unittest
from datetime import datetime, timedelta, timezone
from pathlib import Path

CERT_MGR = Path(
    os.environ.get("CERT_MGR_DIR")
    or Path(__file__).resolve().parents[2] / "rootfs" / "usr" / "lib" / "cert-mgr"
)
sys.path.insert(0, str(CERT_MGR))

import public_cert  # noqa: E402

try:
    import jinja2
except ImportError:  # pragma: no cover - CI's plain Python job
    jinja2 = None

TEMPLATES = CERT_MGR / "templates"
STATIC = CERT_MGR / "static"
#: The only absolute URL the templates may contain (the footer's link).
ALLOWED_ABSOLUTE = {"https://linumiq.com"}
ATTR_URL_RE = re.compile(r'\b(?:href|src|srcset|action|poster|data)="([^"]*)"')
ABSOLUTE_RE = re.compile(r"^(?:[a-z][a-z0-9+.-]*:|//)", re.I)


def css_files() -> list[Path]:
    return sorted(STATIC.rglob("*.css"))


class SharedLayoutTests(unittest.TestCase):
    def test_templates_extend_the_shared_layout(self):
        layout = (TEMPLATES / "_layout.html").read_text()
        self.assertTrue(layout.startswith("{#- GENERATED by scripts/sync-shared.sh"), layout[:80])
        self.assertIn("<!doctype html>", layout)
        self.assertIn('<meta name="color-scheme" content="light dark" />', layout)
        index = (TEMPLATES / "index.html").read_text()
        self.assertTrue(index.startswith('{% extends "_layout.html" %}'))
        for block in ("title", "app_name", "app_subtitle", "flashes", "content", "scripts"):
            self.assertIn(f"{{% block {block}", index, block)
        # The footer is the layout's alone: no "state version N" line (2.1.1).
        self.assertNotIn("footer_extra", index)
        self.assertNotIn("state.version", index)
        # The public certificate card stays a partial (GET public-cert renders it alone).
        self.assertNotIn("extends", (TEMPLATES / "_public_cert.html").read_text())
        self.assertNotIn("<html", (TEMPLATES / "_public_cert.html").read_text())

    def test_layout_loads_the_shared_then_the_app_stylesheet(self):
        layout = (TEMPLATES / "_layout.html").read_text()
        shared = layout.index('<link rel="stylesheet" href="static/shared/linumiq.css" />')
        self.assertLess(shared, layout.index('<link rel="stylesheet" href="static/app.css" />'))
        self.assertIn('src="static/brand/icon.svg"', layout)
        footer = layout[layout.index('<footer class="app-footer">'):]
        for needle in ('href="https://linumiq.com"', 'target="_blank"', 'rel="noopener noreferrer"',
                       'src="static/shared/brand/linumiq-logo.png"', 'alt="LinumIQ"'):
            self.assertIn(needle, footer)

    def test_every_relative_url_of_the_templates_exists(self):
        for template in sorted(TEMPLATES.glob("*.html")):
            for url in ATTR_URL_RE.findall(template.read_text()):
                if url.startswith("static/"):
                    with self.subTest(template=template.name, url=url):
                        self.assertTrue((CERT_MGR / url).is_file(), url)

    def test_templates_never_disable_autoescaping(self):
        for template in sorted(TEMPLATES.glob("*.html")):
            text = template.read_text()
            self.assertIsNone(re.search(r"\|\s*safe\b", text), template.name)
            self.assertNotIn("autoescape false", text)
            self.assertNotIn("Markup", text)


class NoExternalResourcesTests(unittest.TestCase):
    """Nothing is loaded from another host (no Google Fonts, no CDN)."""

    def test_templates(self):
        for template in sorted(TEMPLATES.glob("*.html")):
            text = template.read_text()
            with self.subTest(template=template.name):
                for url in ATTR_URL_RE.findall(text):
                    if ABSOLUTE_RE.match(url):
                        self.assertIn(url, ALLOWED_ABSOLUTE)
                self.assertNotRegex(text, r"url\(|@import|fonts\.googleapis|gstatic")
                self.assertNotRegex(text, r"<script[^>]*\bsrc=")

    def test_stylesheets(self):
        self.assertEqual([p.relative_to(STATIC).as_posix() for p in css_files()],
                         ["app.css", "shared/linumiq.css"])
        for css in css_files():
            text = css.read_text()
            with self.subTest(css=css.name):
                self.assertNotRegex(text, r"https?:|@import|//[a-z]")
                urls = re.findall(r"url\(\s*['\"]?([^'\")]+)", text)
                for url in urls:
                    self.assertTrue((css.parent / url).is_file(), url)
        shared = (STATIC / "shared" / "linumiq.css").read_text()
        self.assertTrue(shared.startswith("/* GENERATED by scripts/sync-shared.sh"))
        self.assertEqual(shared.count("@font-face"), 4)
        self.assertEqual(shared.count("font-display: swap;"), 4)

    def test_app_mark_is_self_contained(self):
        svg = (STATIC / "brand" / "icon.svg").read_text()
        self.assertIn("<svg", svg)
        refs = re.findall(r'\b(?:href|xlink:href)="([^"]*)"', svg)
        self.assertEqual([r for r in refs if not r.startswith("#")], [])
        self.assertNotRegex(svg, r"url\((?!#)|@import|<script")


class FontTests(unittest.TestCase):
    FONTS = ("roboto-latin.woff2", "roboto-latin-ext.woff2", "inter-latin.woff2", "inter-latin-ext.woff2")

    def test_fonts_match_sources_md(self):
        fonts = STATIC / "shared" / "fonts"
        rows = dict(re.findall(r"^\| `([^`]+)` \| \d+ \| `([0-9a-f]{64})` \|", (fonts / "SOURCES.md").read_text(), re.M))
        self.assertEqual(set(rows), set(self.FONTS) | {"OFL-Roboto.txt", "OFL-Inter.txt"})
        total = 0
        for name, digest in rows.items():
            with self.subTest(file=name):
                data = (fonts / name).read_bytes()
                self.assertEqual(hashlib.sha256(data).hexdigest(), digest)
                if name.endswith(".woff2"):
                    self.assertEqual(data[:4], b"wOF2")
                    total += len(data)
        self.assertLess(total, 250_000)
        self.assertIn("SIL Open Font License", (fonts / "OFL-Roboto.txt").read_text())
        self.assertIn("SIL Open Font License", (fonts / "OFL-Inter.txt").read_text())


class ThemeTests(unittest.TestCase):
    def test_dark_token_blocks_are_identical(self):
        css = (STATIC / "shared" / "linumiq.css").read_text()
        media = re.search(r':root:not\(\[data-theme="light"\]\)\s*\{(.*?)\}', css, re.S)
        forced = re.search(r':root\[data-theme="dark"\]\s*\{(.*?)\}', css, re.S)
        self.assertIsNotNone(media)
        self.assertIsNotNone(forced)
        normalise = lambda block: [line.strip() for line in block.strip().splitlines()]  # noqa: E731
        self.assertEqual(normalise(media[1]), normalise(forced[1]))
        self.assertIn("color-scheme: dark;", forced[1])
        self.assertIn("@media (prefers-color-scheme: dark)", css)
        self.assertIn("@media (prefers-reduced-motion: reduce)", css)

    def test_buttons_are_blue_in_both_modes(self):
        """The owner's rule of 2026-10-29: buttons are blue as on
        shop.linumiq.com - Anchor Blue in light mode, the shop's #60A4FA in
        dark mode, white text in both - and no button is orange (the
        call-to-action class .btn-cta is gone)."""
        css = re.sub(r"/\*.*?\*/", "", (STATIC / "shared" / "linumiq.css").read_text(), flags=re.S)
        light = re.search(r"^:root\s*\{(.*?)^\}", css, re.S | re.M)[1]
        self.assertIn("--li-anchor-blue: #0883da;", light)
        self.assertIn("--color-button: var(--li-anchor-blue);", light)
        self.assertIn("--color-on-button: #ffffff;", light)
        dark = re.search(r':root\[data-theme="dark"\]\s*\{(.*?)\}', css, re.S)[1]
        self.assertIn("--color-button: #60a4fa;", dark)
        self.assertNotIn("--color-on-button", dark)  # white text in both modes
        btn = re.search(r"^\.btn\s*\{(.*?)\}", css, re.S | re.M)[1]
        self.assertIn("background: var(--color-button);", btn)
        self.assertIn("color: var(--color-on-button);", btn)
        for sheet in css_files():
            text = re.sub(r"/\*.*?\*/", "", sheet.read_text(), flags=re.S)
            self.assertNotIn("btn-cta", text, sheet.name)
            for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", text):
                if "btn" in selector or "button" in selector:
                    with self.subTest(css=sheet.name, selector=selector.strip()):
                        self.assertNotRegex(body, r"accent|orange|--color-warn|#ff9d0b|#f08c00")


@unittest.skipIf(jinja2 is None, "Jinja2 not installed (run inside the add-on image)")
class RenderTests(unittest.TestCase):
    """The dashboard and the card as the panel renders them."""

    NOW = datetime(2026, 10, 28, 12, 0, tzinfo=timezone.utc).timestamp()

    @classmethod
    def setUpClass(cls):
        cls.env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(TEMPLATES)), autoescape=True)

    def _pc(self, state: str) -> public_cert.Status:
        runtime = public_cert.Runtime(domain="home.example.org", started_at=self.NOW - 600,
                                      host_ports_known=True, http_host_port=8080, https_host_port=8443)
        cert = public_cert.Certificate(
            path="/data/caddy/x.crt", subject_cn="home.example.org", issuer_cn="R12",
            issuer_org="Let's Encrypt", not_after=datetime.fromtimestamp(self.NOW, timezone.utc) + timedelta(days=60),
            fingerprint_sha256="ab" * 32, mtime=self.NOW - 3600)
        error = public_cert.AcmeEvent(ts=self.NOW - 60, logger="tls.obtain", level="error",
                                      msg="could not get certificate from issuer",
                                      error="86.62.32.88: Timeout during connect", problem_type="connection")
        if state == "ok":
            return public_cert.Status(state="ok", runtime=runtime, certificate=cert, served=True, now=self.NOW)
        return public_cert.Status(state="missing", runtime=runtime, last_error=error, now=self.NOW)

    def _context(self, state: str) -> dict:
        pc = self._pc(state)
        return {
            "state": {"version": 2, "ca": None, "clients": [
                {"name": "alice", "status": "active", "serial": "01", "not_after": "2027-10-28"},
                {"name": "bob", "status": "revoked", "serial": "02", "revocation_reason": "superseded"},
            ], "crl_number": 3, "crl_generated_at": "2026-10-28T10:00:00Z"},
            "ca_crt_exists": True, "crl_exists": True, "flash_error": "<b>x</b>", "flash_ok": None,
            "pc": pc, "pc_checklist": public_cert.checklist(pc), "pc_retry_hint": public_cert.retry_hint(pc),
            "pc_time": public_cert.local_time,
        }

    def test_dashboard(self):
        for state in ("ok", "missing"):
            with self.subTest(state=state):
                html = self.env.get_template("index.html").render(self._context(state))
                self.assertTrue(html.startswith("<!doctype html>"), html[:60])
                self.assertIn("<title>Caddy mTLS - Certificate Manager</title>", html)
                self.assertIn("<h1>Caddy mTLS</h1>", html)
                self.assertIn('class="app-header__mark"', html)
                self.assertNotIn("\U0001f510", html)  # the old emoji header icon
                self.assertIn(f'data-state="{state}"', html)
                self.assertLess(html.index('id="public-cert"'), html.index("Certificate Authority"))
                self.assertIn("&lt;b&gt;x&lt;/b&gt;", html)
                footer = html[html.index('<footer class="app-footer">'):]
                self.assertIn('src="static/shared/brand/linumiq-logo.png"', footer)
                self.assertNotIn("state version", html)
                # Only the logo link is in the footer (2.1.1: no app lines).
                self.assertNotIn("<p", footer[:footer.index("</footer>")])
                self.assertIn('fetch("public-cert"', html[html.index("</footer>"):])
                for url in ATTR_URL_RE.findall(html):
                    if ABSOLUTE_RE.match(url):
                        self.assertIn(url, ALLOWED_ABSOLUTE)

    def test_card_alone_is_a_fragment(self):
        html = self.env.get_template("_public_cert.html").render(self._context("missing"))
        self.assertTrue(html.lstrip().startswith("<section"), html[:60])
        self.assertIn('class="card pc pc--missing"', html)
        self.assertNotIn("<html", html)
        self.assertNotIn("app-footer", html)


if __name__ == "__main__":
    unittest.main()
