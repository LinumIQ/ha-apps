#!/usr/bin/env bash
# ==============================================================================
# Copies the shared LinumIQ panel UI into both add-ons.
#
# usage: scripts/sync-shared.sh            update the copies
#        scripts/sync-shared.sh --check    exit 1 (and list them) if a copy is stale
#
# The build context of an add-on image is the add-on directory alone, so the
# shared sources cannot be referenced from there (no paths or symlinks out of
# it): they are copied, and CI ("Shared UI in sync") runs --check.
#
#   shared/ui/static/                -> <add-on>/rootfs/usr/lib/<panel>/static/shared/
#                                       (replaced as a whole: removed files disappear)
#   shared/ui/templates/_layout.html -> <add-on>/rootfs/usr/lib/<panel>/templates/_layout.html
#   shared/brand/<add-on>/icon.svg   -> <add-on>/rootfs/usr/lib/<panel>/static/brand/icon.svg
#
# for frp-tunnel (panel frp-mgr) and caddy-mtls (panel cert-mgr). The copied
# stylesheets and the template get a GENERATED comment as their first line;
# never edit the copies, edit shared/ and run this script.
#
# --check syncs into a temporary directory and compares it with the tree
# (diff -r); exit 0 = in sync, 1 = stale copies (listed), 2 = usage error.
# ==============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHARED_UI="${ROOT}/shared/ui"
BRAND="${ROOT}/shared/brand"
# <add-on directory>:<panel directory under rootfs/usr/lib>
PANELS=("frp-tunnel:frp-mgr" "caddy-mtls:cert-mgr")
GENERATED="GENERATED by scripts/sync-shared.sh"

usage() { printf 'usage: %s [--check]\n' "${0##*/}" >&2; exit 2; }

# The repository-relative paths this script writes (per add-on).
managed_paths() {
    local entry addon panel
    for entry in "${PANELS[@]}"; do
        addon="${entry%%:*}"
        panel="${entry#*:}"
        printf '%s\n' \
            "${addon}/rootfs/usr/lib/${panel}/static/shared" \
            "${addon}/rootfs/usr/lib/${panel}/templates/_layout.html" \
            "${addon}/rootfs/usr/lib/${panel}/static/brand/icon.svg"
    done
}

# sync_into <root>: write every copy below <root> (the repository root, or a
# temporary directory that mirrors it).
sync_into() {
    local dest="$1" entry addon panel lib css rel
    [[ -f "${SHARED_UI}/templates/_layout.html" ]] || { printf 'missing %s\n' "shared/ui/templates/_layout.html" >&2; return 1; }
    for entry in "${PANELS[@]}"; do
        addon="${entry%%:*}"
        panel="${entry#*:}"
        lib="${dest}/${addon}/rootfs/usr/lib/${panel}"
        [[ -f "${BRAND}/${addon}/icon.svg" ]] || { printf 'missing %s\n' "shared/brand/${addon}/icon.svg" >&2; return 1; }
        mkdir -p "${lib}/static/brand" "${lib}/templates"

        rm -rf "${lib}/static/shared"
        cp -R "${SHARED_UI}/static" "${lib}/static/shared"
        while IFS= read -r -d '' css; do
            rel="${css#"${lib}/static/shared/"}"
            {
                printf '/* %s - edit shared/ui/static/%s instead. */\n' "${GENERATED}" "${rel}"
                cat "${SHARED_UI}/static/${rel}"
            } >"${css}"
        done < <(find "${lib}/static/shared" -type f -name '*.css' -print0)

        {
            printf '{#- %s - edit shared/ui/templates/_layout.html instead. -#}\n' "${GENERATED}"
            cat "${SHARED_UI}/templates/_layout.html"
        } >"${lib}/templates/_layout.html"

        cp "${BRAND}/${addon}/icon.svg" "${lib}/static/brand/icon.svg"
    done
}

TMP_DIR=""
cleanup() { [[ -z "${TMP_DIR}" ]] || rm -rf "${TMP_DIR}"; }
trap cleanup EXIT

check() {
    local path line stale=0
    TMP_DIR="$(mktemp -d)"
    sync_into "${TMP_DIR}"
    while IFS= read -r path; do
        if [[ ! -e "${ROOT}/${path}" ]]; then
            printf 'missing: %s\n' "${path}"
            stale=1
            continue
        fi
        # diff -rq prints "Files A and B differ" and "Only in DIR: NAME".
        while IFS= read -r line; do
            stale=1
            case "${line}" in
                "Only in ${TMP_DIR}/"*)
                    line="${line#"Only in ${TMP_DIR}/"}"
                    printf 'missing: %s/%s\n' "${line%%: *}" "${line#*: }" ;;
                "Only in ${ROOT}/"*)
                    line="${line#"Only in ${ROOT}/"}"
                    printf 'not in shared/ (remove it): %s/%s\n' "${line%%: *}" "${line#*: }" ;;
                "Files ${TMP_DIR}/"*)
                    line="${line#"Files ${TMP_DIR}/"}"
                    printf 'stale: %s\n' "${line%% and *}" ;;
                *) printf 'differs: %s\n' "${line}" ;;
            esac
        done < <(diff -rq "${TMP_DIR}/${path}" "${ROOT}/${path}" || true)
    done < <(managed_paths)
    if (( stale )); then
        printf 'The shared UI copies are out of date: run scripts/sync-shared.sh and commit the result.\n' >&2
        return 1
    fi
    printf 'Shared UI copies are in sync (%d paths).\n' "$(managed_paths | wc -l)"
}

case "${1:-}" in
    "") sync_into "${ROOT}"; printf 'Synced the shared UI into: %s\n' "$(printf '%s ' "${PANELS[@]%%:*}")" ;;
    --check) [[ $# -eq 1 ]] || usage; check ;;
    *) usage ;;
esac
