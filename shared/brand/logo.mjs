#!/usr/bin/env node
// Builds shared/brand/<addon>/logo.svg (500x200) from shared/brand/<addon>/icon.svg and the
// add-on name (exactly `name:` of <addon>/config.yaml) set in Roboto Bold and converted to
// outlines, so rendering never depends on an installed font. See README.md.
//
//   node logo.mjs --font /path/to/Roboto-Bold.ttf           write both logo.svg files
//   node logo.mjs --font /path/to/Roboto-Bold.ttf --check   fail if a committed logo.svg differs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
// Roboto-Bold.ttf from roboto-unhinted.zip of github.com/googlefonts/roboto-2 release v2.138
const FONT_SHA256 = '2ca2b3bfc2c2d43fa8f2b7227982d735fd537ecf113a4c56cc2d292bcc3106c8';
const FONT_LABEL = 'Roboto Bold 2.138';
const BLUE = '#0883DA';

// Layout (500x200 canvas): the ring is 140 px high (icon scale 140/240), 30 px from the left
// edge and vertically centred; the name starts 28 px right of the ring, 48 px Roboto Bold.
const W = 500, H = 200, RING = 140, MARGIN = 30, GAP = 28, SIZE = 48, LEADING = 56;
const SCALE = RING / 240; // the ring spans 8..248 of the 256 icon viewBox
const LOGOS = [
  { addon: 'frp-tunnel', lines: ['FRP Tunnel'] },
  { addon: 'caddy-mtls', lines: ['Caddy mTLS', 'Proxy'] }, // one line would need 32 px type
];

const args = process.argv.slice(2);
const check = args.includes('--check');
const fontPath = args[args.indexOf('--font') + 1];
if (!args.includes('--font') || !fontPath) {
  console.error('usage: node logo.mjs --font /path/to/Roboto-Bold.ttf [--check]');
  process.exit(2);
}
const fontBuf = readFileSync(fontPath);
const sha = createHash('sha256').update(fontBuf).digest('hex');
if (sha !== FONT_SHA256) {
  console.error(`font sha256 ${sha} does not match the pinned ${FONT_SHA256} (${FONT_LABEL})`);
  process.exit(2);
}
const font = opentype.parse(fontBuf.buffer.slice(fontBuf.byteOffset, fontBuf.byteOffset + fontBuf.byteLength));
const capHeight = (font.tables.os2.sCapHeight / font.unitsPerEm) * SIZE;
const r = (n) => Math.round(n * 100) / 100;

function build({ addon, lines }) {
  const name = readFileSync(join(REPO, addon, 'config.yaml'), 'utf8').match(/^name:\s*"([^"]+)"/m)[1];
  if (lines.join(' ') !== name) throw new Error(`${addon}: logo text "${lines.join(' ')}" != config.yaml name "${name}"`);
  const icon = readFileSync(join(HERE, addon, 'icon.svg'), 'utf8');
  const inner = icon.replace(/^\s*<svg[^>]*>\n/, '').replace(/<\/svg>\s*$/, '').trimEnd()
    .split('\n').map((l) => `  ${l}`).join('\n');
  const textX = MARGIN + RING + GAP;
  // centre the block between the cap top of the first line and the baseline of the last
  const firstBaseline = H / 2 - (capHeight + (lines.length - 1) * LEADING) / 2 + capHeight;
  const d = lines.map((line, i) => {
    const inkLeft = font.getPath(line, 0, 0, SIZE).getBoundingBox().x1; // align the ink, not the side bearing
    return font.getPath(line, textX - inkLeft, firstBaseline + i * LEADING, SIZE).toPathData(2);
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- generated by shared/brand/logo.mjs from icon.svg; edit icon.svg or logo.mjs, not this file -->
  <g transform="translate(${r(MARGIN - 8 * SCALE)} ${r(H / 2 - 128 * SCALE)}) scale(${Math.round(SCALE * 1e5) / 1e5})">
${inner}
  </g>
  <!-- "${name}": ${FONT_LABEL}, ${SIZE} px, converted to outlines -->
  <path fill="${BLUE}" d="${d}"/>
</svg>
`;
}

let failed = false;
for (const logo of LOGOS) {
  const out = join(HERE, logo.addon, 'logo.svg');
  const svg = build(logo);
  if (check) {
    let cur = '';
    try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (cur !== svg) { console.error(`DIFFERS  ${logo.addon}/logo.svg`); failed = true; } else console.log(`ok       ${logo.addon}/logo.svg`);
  } else {
    writeFileSync(out, svg);
    console.log(`wrote    ${logo.addon}/logo.svg (${svg.length} bytes)`);
  }
}
process.exit(failed ? 1 : 0);
